import { launch, ensureDoctor, shot, text, log, clickText, UID, fsGet, docOf } from './lib.mjs';
const b = await launch(); const { page } = await ensureDoctor(b, 'doc1');
await clickText(page, /^profile$/i); await page.waitForTimeout(4000);
const name = page.locator('input').filter({ visible: true }).nth(0);
const oldName = await name.inputValue();
await name.fill('   ');
await clickText(page, /^Save Profile$/); await page.waitForTimeout(3000);
const t = await text(page);
log('rerun blank(spaces) name feedback:', t.match(/(Saved ✓|We could not[^\n]*|Complete every[^\n]*|Please[^\n]*)/g));
await shot(page, 'a08c-blank-name-rerun');
const p = docOf((await fsGet(`Providers/${UID.doc1}`)).body); const u = docOf((await fsGet(`Users/${UID.doc1}`)).body);
log('Providers.full_name=', JSON.stringify(p.full_name), 'Users.full_name=', JSON.stringify(u.full_name));
await clickText(page, /^home$/i); await page.waitForTimeout(3000);
log('home header:', (await text(page)).slice(0, 60).replace(/\n/g,' | ')); await shot(page, 'a08c-home-blank-name');
await clickText(page, /^profile$/i); await page.waitForTimeout(3000);
await page.locator('input').filter({ visible: true }).nth(0).fill(oldName);
await clickText(page, /^Save Profile$/); await page.waitForTimeout(3000);
log('restored:', JSON.stringify(docOf((await fsGet(`Providers/${UID.doc1}`)).body).full_name), JSON.stringify(docOf((await fsGet(`Users/${UID.doc1}`)).body).full_name));
await b.close();
